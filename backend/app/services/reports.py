"""Report rendering: investigation -> Markdown, Markdown -> PDF."""

from __future__ import annotations

import io
import re
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, Preformatted, SimpleDocTemplate, Spacer, Table, TableStyle

from app.analytics.metrics import METRICS, format_value


def _esc_md(s: str) -> str:
    return str(s).replace("|", "\\|")


def analysis_to_markdown(a: dict) -> str:
    q = a["question"]
    e = a.get("explanation") or {}
    res = a.get("result") or {}
    calc = res.get("calculations") or {}
    periods = res.get("periods") or {}
    lines = [f"# {a.get('title') or q}", ""]
    lines.append(f"**Question:** {q}  ")
    lines.append(f"**Status:** {a['status']}  ")
    lines.append(f"**Mode:** {'LLM' if a['mode'] == 'llm' else 'Demo (rule-based, no LLM call)'}  ")
    lines.append(f"**Executed:** {a['created_at']}  ")
    lines.append(f"**Data as of:** {a.get('data_as_of') or 'n/a'}  ")
    if periods.get("current"):
        lines.append(f"**Period:** {periods['current']['label']}  ")
    if periods.get("comparison"):
        lines.append(f"**Compared with:** {periods['comparison']['label']}  ")
    if a.get("dataset_is_synthetic"):
        lines.append("**Data:** SYNTHETIC demo dataset  ")
    lines.append("")
    if a.get("error_message"):
        lines += ["## Outcome", "", a["error_message"], ""]
    if e:
        lines += ["## Summary", "", e["summary"]["text"], ""]
        km = calc.get("key_metrics") or []
        if km:
            lines += ["## Key metrics", ""]
            if "comparison" in km[0]:
                lines += ["| Metric | Comparison | Current | Change | % change |", "|---|---:|---:|---:|---:|"]
                for k in km:
                    lines.append(f"| {k['label']} | {k['comparison_display']} | {k['current_display']} | "
                                 f"{k['abs_change_display']} | {k['pct_change_display']} |")
            else:
                lines += ["| Metric | Value |", "|---|---:|"]
                for k in km:
                    lines.append(f"| {k['label']} | {k['current_display']} |")
            lines.append("")
        for title, key in (("Observed facts", "observed_facts"), ("Calculated contributions", "contributions"),
                           ("Possible explanations (hypotheses, not findings)", "possible_explanations"),
                           ("Recommended actions", "recommended_actions")):
            items = e.get(key) or []
            if items:
                lines += [f"## {title}", ""]
                for it in items:
                    extra = f" _(confidence: {it['confidence']})_" if it.get("confidence") else ""
                    lines.append(f"- {it['text']}{extra}")
                lines.append("")
        for mk, cr in (calc.get("contributions") or {}).items():
            if cr.get("segments"):
                lines += [f"### Contribution detail — {METRICS[mk].label}", "", f"_Method: {cr['method']}_", "",
                          "| Segment | Comparison | Current | Contribution |", "|---|---:|---:|---:|"]
                for sg in sorted(cr["segments"], key=lambda x: -abs(x["contribution"]))[:12]:
                    lines.append(f"| {_esc_md(sg['label'])} | {format_value(mk, sg['comparison'])} | "
                                 f"{format_value(mk, sg['current'])} | {sg['contribution']:+,.4g} |")
                lines.append("")
        lims = list(dict.fromkeys((e.get("computed_limitations") or []) + (e.get("limitations") or [])))
        if lims:
            lines += ["## Limitations", ""] + [f"- {x}" for x in lims] + [""]
    if a.get("generated_sql"):
        lines += ["## SQL (validated, executed on a read-only connection)", "", "```sql", a["generated_sql"], "```", ""]
    lines.append(f"_Generated by AI Workmate on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}. "
                 "Numbers come from database queries; narrative numbers are verified against computed facts._")
    return "\n".join(lines) + "\n"


def _inline(s: str) -> str:
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<!\w)_(.+?)_(?!\w)", r"<i>\1</i>", s)
    s = re.sub(r"`(.+?)`", r"<font face='Courier'>\1</font>", s)
    return s


def markdown_to_pdf(md: str, title: str) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title=title, author="AI Workmate")
    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9.5, leading=13)
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], fontSize=16, spaceAfter=6, textColor=colors.HexColor("#111827"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, spaceBefore=8, textColor=colors.HexColor("#1f2937"))
    h3 = ParagraphStyle("h3", parent=ss["Heading3"], fontSize=10.5, spaceBefore=6)
    code = ParagraphStyle("c", parent=ss["Code"], fontSize=7.5, leading=9.5, backColor=colors.HexColor("#f3f4f6"))
    story = []
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("```"):
            j = i + 1
            block = []
            while j < len(lines) and not lines[j].startswith("```"):
                block.append(lines[j])
                j += 1
            story.append(Preformatted("\n".join(block), code))
            i = j + 1
            continue
        if ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", lines[i].strip().strip("|"))]
                if not all(set(c) <= set("-:") for c in cells):
                    rows.append([Paragraph(_inline(c), body) for c in cells])
                i += 1
            if rows:
                t = Table(rows, repeatRows=1)
                t.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f4f6")),
                    ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ]))
                story += [t, Spacer(1, 4)]
            continue
        if ln.startswith("# "):
            story.append(Paragraph(_inline(ln[2:]), h1))
        elif ln.startswith("## "):
            story.append(Paragraph(_inline(ln[3:]), h2))
        elif ln.startswith("### "):
            story.append(Paragraph(_inline(ln[4:]), h3))
        elif ln.startswith("- "):
            story.append(Paragraph("• " + _inline(ln[2:]), body))
        elif ln.strip():
            story.append(Paragraph(_inline(ln.rstrip(" ")), body))
        else:
            story.append(Spacer(1, 4))
        i += 1
    doc.build(story)
    return buf.getvalue()
