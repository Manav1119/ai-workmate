"""Generate docs/EXAMPLE_QUESTIONS.md from REAL pipeline output (no hand-written answers).

    python -m eval.examples          (from backend/, DB seeded)
"""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy import text

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.db import app_tx  # noqa: E402
from app.llm.providers import get_provider  # noqa: E402
from app.pipeline.orchestrator import run_analysis  # noqa: E402
from app.security.auth import dataset_for_user, load_user  # noqa: E402
from eval.run_eval import NOW, ensure_eval_user  # noqa: E402

QUESTIONS = [
    "Why did conversions fall last week?",
    "Which campaigns contributed most to the increase in CPA?",
    "Compare this week with the previous week",
    "Which campaigns have high spend but low conversion rates?",
    "Show the daily ROAS trend for the last 30 days",
    "Are there any unusual changes in campaign performance?",
    "Which campaigns contributed most to the revenue decline?",
    "What is our customer churn rate?",
    "DROP TABLE campaigns",
]


def main() -> None:
    provider = get_provider()
    user = load_user(ensure_eval_user())
    ds = dataset_for_user(user, None)
    mode = "LLM" if provider else "demo (rule-based interpreter, template narrative, no LLM call)"
    out = ["# Example questions and actual answers", "",
           f"Generated by `python -m eval.examples` in **{mode}** mode against the SYNTHETIC demo dataset, with the "
           "clock fixed to 2026-10-24 (data runs through 2026-10-18). Answers below are copied from the pipeline output, "
           "not written by hand. Expected values for a larger set of questions are checked automatically by "
           "`eval/run_eval.py` against an independent pandas oracle.", ""]
    for q in QUESTIONS:
        aid = run_analysis(user=user, dataset=ds, question=q, provider=provider, now=NOW)
        with app_tx() as c:
            a = dict(c.execute(text("SELECT * FROM app.analyses WHERE id = :i"), {"i": aid}).mappings().one())
        out += [f"## {q}", "", f"**Status:** {a['status']}  ", f"**Intent:** {a['intent']}", ""]
        e = a.get("explanation")
        if e:
            out += [f"> {e['summary']['text']}", ""]
            for title, key in (("Calculated contributions", "contributions"), ("Possible explanations", "possible_explanations"),
                               ("Recommended actions", "recommended_actions")):
                if e.get(key):
                    out += [f"**{title}**", ""] + [f"- {s['text']}" for s in e[key][:3]] + [""]
            out += ["**Limitations**", ""] + [f"- {x}" for x in e.get("computed_limitations", [])[:5]] + [""]
        else:
            out += [f"> {a['error_message']}", ""]
        if a.get("generated_sql"):
            out += ["<details><summary>Validated SQL</summary>", "", "```sql", a["generated_sql"], "```", "", "</details>", ""]
    target = Path(__file__).resolve().parents[2] / "docs" / "EXAMPLE_QUESTIONS.md"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
